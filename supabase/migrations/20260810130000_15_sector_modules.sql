-- ═══════════════════════════════════════════════════════════════════════════
-- 15 — Tables for the sixteen modules added in migration 14
--
-- Conventions, all inherited from migrations 02 and 03 rather than reinvented:
--
--   · Every top-level entity carries `org_id` and gets `app.apply_standard_rls`.
--     Line items and other rows that only exist inside a parent get
--     `app.apply_child_rls`, which reads isolation off the parent instead of
--     duplicating an org_id that could disagree with it.
--   · Money is `bigint` minor units, never numeric and never text.
--   · Soft delete via `deleted_at` on anything a user can remove by mistake;
--     line items are hard-deleted with their parent, since a "deleted" invoice
--     line that still counts toward a total is a bug, not a record.
--   · Human-readable codes come from `app.set_code`, so they are unique per
--     organization and never collide across tenants.
--   · Enumerated columns match the vocabularies in src/lib/domain.ts exactly,
--     accents included: the constraint compares literal strings.
--
-- Not every module here starts from nothing. Migration 02 already created
-- `job_openings`, `candidates`, `courses`, `course_enrollments`,
-- `certifications` and `evaluations` — thin scaffolding, gated on
-- `empleados:read/write`, with no query, mutation or seed reading them. Those
-- are widened and re-pointed at their own module permission below rather than
-- duplicated: a second `candidates` table would have made "how many people
-- applied" a question with two answers.
-- ═══════════════════════════════════════════════════════════════════════════

/**
 * Moves a table from one permission pair to another.
 *
 * `app.apply_standard_rls` creates policies with fixed, derived names, so the
 * old four can be dropped by name and the new four generated by the same
 * function the rest of the schema uses. Re-pointing by hand would mean writing
 * the four policy bodies again, which is how one of them ends up subtly
 * different from every other table in the database.
 */
create or replace function app.repoint_standard_rls(
  p_table      text,
  p_read_perm  text,
  p_write_perm text
)
returns void
language plpgsql
as $$
begin
  execute format('drop policy if exists %I on public.%I', p_table || '_select', p_table);
  execute format('drop policy if exists %I on public.%I', p_table || '_insert', p_table);
  execute format('drop policy if exists %I on public.%I', p_table || '_update', p_table);
  execute format('drop policy if exists %I on public.%I', p_table || '_delete', p_table);
  perform app.apply_standard_rls(p_table, p_read_perm, p_write_perm);
end;
$$;

create or replace function app.repoint_child_rls(
  p_table        text,
  p_parent_table text,
  p_fk_column    text,
  p_read_perm    text,
  p_write_perm   text
)
returns void
language plpgsql
as $$
begin
  execute format('drop policy if exists %I on public.%I', p_table || '_select', p_table);
  execute format('drop policy if exists %I on public.%I', p_table || '_insert', p_table);
  execute format('drop policy if exists %I on public.%I', p_table || '_update', p_table);
  execute format('drop policy if exists %I on public.%I', p_table || '_delete', p_table);
  perform app.apply_child_rls(p_table, p_parent_table, p_fk_column, p_read_perm, p_write_perm);
end;
$$;

revoke all on function app.repoint_standard_rls(text, text, text) from public, anon, authenticated;
revoke all on function app.repoint_child_rls(text, text, text, text, text) from public, anon, authenticated;

