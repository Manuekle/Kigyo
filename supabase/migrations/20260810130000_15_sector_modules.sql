-- Reclutamiento
-- ═══════════════════════════════════════════════════════════════════════════

-- `job_openings` and `candidates` already exist (migration 02). Widened here
-- into a module rather than replaced: the FK column stays `job_opening_id`,
-- because renaming a column nothing has read yet is churn, and renaming one
-- something HAS read is a break.

alter table public.job_openings
  add column location text not null default '',
  add column openings smallint not null default 1 check (openings between 1 and 999),
  add column salary_min_cents bigint not null default 0 check (salary_min_cents >= 0),
  add column salary_max_cents bigint not null default 0 check (salary_max_cents >= 0),
  add column hiring_manager_id uuid references public.employees (id) on delete set null,
  add column description text not null default '',
  add column closed_on date,
  add column deleted_at timestamptz,
  add constraint job_openings_salary_ordered
    check (salary_max_cents = 0 or salary_max_cents >= salary_min_cents);

-- The old vocabulary ('Activo', 'Pausado', 'Cerrado') described whether the
-- posting was live. The new one describes where the search is, which is what
-- the board columns key off. Existing rows are mapped rather than left to
-- violate the new constraint — an ALTER that fails on real data is a migration
-- that only works on an empty database.
update public.job_openings set status = case status
  when 'Activo'  then 'Abierta'
  when 'Pausado' then 'En proceso'
  when 'Cerrado' then 'Cerrada'
  else status
end;

alter table public.job_openings
  drop constraint if exists job_openings_status_check;
alter table public.job_openings
  alter column status set default 'Abierta',
  add constraint job_openings_status_check
    check (status in ('Abierta', 'En proceso', 'Cerrada', 'Cancelada'));

create index job_openings_org_idx on public.job_openings (org_id, status)
  where deleted_at is null;

select app.repoint_standard_rls('job_openings', 'reclutamiento:read', 'reclutamiento:write');

alter table public.candidates
  add column phone text not null default '',
  add column rating smallint check (rating is null or rating between 1 and 5),
  add column expected_salary_cents bigint not null default 0
    check (expected_salary_cents >= 0),
  add column resume_url text,
  add column notes text not null default '',
  add column applied_on date not null default current_date,
  -- Set when the candidate reaches 'Contratado' and an employee row is created
  -- from them, so the funnel can report conversion without guessing by name.
  add column employee_id uuid references public.employees (id) on delete set null;

update public.candidates set stage = case stage
  when 'Aplicación' then 'Postulado'
  when 'Revisión'   then 'Preselección'
  else stage
end;

alter table public.candidates
  drop constraint if exists candidates_stage_check;
alter table public.candidates
  alter column stage set default 'Postulado',
  add constraint candidates_stage_check
    check (stage in ('Postulado', 'Preselección', 'Entrevista', 'Prueba',
                     'Oferta', 'Contratado', 'Descartado'));

select app.repoint_child_rls('candidates', 'job_openings', 'job_opening_id',
                             'reclutamiento:read', 'reclutamiento:write');

