-- Facturación
--
-- `total_cents` is stored, not computed on read. A historical invoice must
-- keep the total it was issued with even after a product's price changes, and
-- a view that recomputes it from today's catalogue quietly rewrites the past.
-- ═══════════════════════════════════════════════════════════════════════════

create table public.invoices (
  id             uuid primary key default gen_random_uuid(),
  org_id         uuid not null references public.organizations (id) on delete cascade,
  code           text,
  client_id      uuid references public.clients (id) on delete set null,
  -- Kept alongside the FK: an invoice must still print the name it was issued
  -- to even if the client row is later removed.
  client_name    text not null default '',
  quote_id       uuid references public.quotes (id) on delete set null,
  project_id     uuid references public.projects (id) on delete set null,
  status         text not null default 'Borrador'
                   check (status in ('Borrador', 'Emitida', 'Pagada', 'Vencida', 'Anulada')),
  issued_on      date not null default current_date,
  due_on         date,
  subtotal_cents bigint not null default 0 check (subtotal_cents >= 0),
  tax_cents      bigint not null default 0 check (tax_cents >= 0),
  total_cents    bigint not null default 0 check (total_cents >= 0),
  paid_cents     bigint not null default 0 check (paid_cents >= 0),
  currency       text not null default 'COP' check (currency ~ '^[A-Z]{3}$'),
  notes          text not null default '',
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now(),
  deleted_at     timestamptz,
  unique (org_id, code),
  constraint invoices_dates_ordered check (due_on is null or due_on >= issued_on),
  -- Overpayment is a data-entry error, not a state the reports should carry.
  constraint invoices_paid_within_total check (paid_cents <= total_cents)
);

create index invoices_org_idx on public.invoices (org_id, status) where deleted_at is null;
create index invoices_client_idx on public.invoices (client_id) where deleted_at is null;
create index invoices_due_idx on public.invoices (org_id, due_on)
  where deleted_at is null and status in ('Emitida', 'Vencida');

create trigger invoices_code  before insert on public.invoices
  for each row execute function app.set_code('invoice', 'FAC', '5');
create trigger invoices_touch before update on public.invoices
  for each row execute function app.touch_updated_at();

select app.apply_standard_rls('invoices', 'facturacion:read', 'facturacion:write');

